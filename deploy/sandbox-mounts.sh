#!/usr/bin/env bash
# Run on the VPS by the deploy before `up -d`. The sandbox (WhatsApp and API chats) binds
# some workspace folders read-only straight from the volume, and a bind to a missing folder
# stops the stack from starting, so this creates them. Compose cannot glob, so the
# per-agent folders (agents/<id>/knowledge, agents/<id>/skills) go into a generated
# override, deploy/compose.sandbox.yaml, used with: -f deploy/compose.yaml -f deploy/compose.sandbox.yaml
set -euo pipefail
cd "$HOME/cowagent"
VOLUME=cowagent_workspace
DATA="/var/lib/docker/volumes/$VOLUME/_data"
OUT=deploy/compose.sandbox.yaml

# Labelled as compose would, so compose adopts it instead of warning on a fresh server.
sudo -n docker volume inspect "$VOLUME" >/dev/null 2>&1 \
  || sudo -n docker volume create --label com.docker.compose.project=cowagent --label com.docker.compose.volume=workspace "$VOLUME" >/dev/null

# A bind source is resolved on the host, so a symlink there could expose host files: refuse it.
dirs="$(sudo -n docker run --rm -v "$VOLUME":/v alpine:3.20 sh -c '
  set -e; cd /v
  for d in knowledge scheduler skills; do
    if [ -L "$d" ]; then echo "symlink:$d"; exit 0; fi
    [ -d "$d" ] || { mkdir -p "$d"; chown 999:999 "$d"; }
  done
  for d in agents/*/knowledge agents/*/skills; do
    [ -d "$d" ] && [ ! -L "$d" ] && echo "$d"
  done
  true')"
if grep -q '^symlink:' <<<"$dirs"; then
  echo "::error::workspace folder ${dirs#symlink:} is a symlink; the sandbox will not bind it" >&2
  exit 1
fi

{
  echo '# Generated by deploy/sandbox-mounts.sh on every deploy; do not edit.'
  echo 'services:'
  echo '  sandbox:'
  echo '    volumes:'
  found=0
  while IFS= read -r d; do
    # Agent ids are plain names; anything else is skipped rather than quoted into YAML.
    [[ "$d" =~ ^agents/[A-Za-z0-9_.-]+/(knowledge|skills)$ ]] || continue
    # agents/personal is masked by a tmpfs in compose.yaml; a bind inside it would unmask it.
    [[ "$d" == agents/personal/* ]] && continue
    found=1
    printf '      - type: bind\n        source: %s/%s\n        target: /home/agent/cow/%s\n        read_only: true\n        bind: { create_host_path: false }\n' "$DATA" "$d" "$d"
  done <<<"$dirs"
  (( found )) || echo '      []'
} > "$OUT.tmp"
mv -f "$OUT.tmp" "$OUT"
echo "sandbox read-only per-agent folders: $(grep -c 'type: bind' "$OUT" || true)"
